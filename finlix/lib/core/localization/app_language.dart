class AppLanguage {
  static final AppLanguage instance = AppLanguage._init();
  AppLanguage._init();

  /// ValueNotifier to trigger reactive updates across the whole app
  final ValueNotifier<String> localeNotifier = ValueNotifier<String>('id');

  String get currentCode => localeNotifier.value;
  bool get isIndonesian => localeNotifier.value == 'id';

  Future<void> init() async {
    try {
      final saved = await DbHelper.instance.getSetting('language');
      if (saved == 'en' || saved == 'id') {
        localeNotifier.value = saved!;
      } else {
        localeNotifier.value = 'id'; // default Bahasa Indonesia
      }
    } catch (_) {
      localeNotifier.value = 'id';
    }
  }

  Future<void> setLanguage(String code) async {
    if (code != 'en' && code != 'id') return;
    localeNotifier.value = code;
    try {
      await DbHelper.instance.setSetting('language', code);
    } catch (_) {}
  }

